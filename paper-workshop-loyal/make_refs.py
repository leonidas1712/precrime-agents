#!/usr/bin/env python3
"""Write refs.bib: the arXiv paper's references.bib, minus eprint fields that repeat.

The AAAI bibliography style prints the eprint after the other fields. An entry
whose howpublished, journal or note already names the arXiv id would show it twice,
so the eprint fields are dropped from those entries only.
"""
import re
from pathlib import Path

here = Path(__file__).resolve().parent
src = (here / '../paper-arxiv/references.bib').read_text()
entries = re.split(r'(?m)^(?=@)', src)
out, dropped, kept = [], 0, 0
for entry in entries:
    m = re.search(r'(?m)^\s*eprint\s*=\s*[{"]([^}"]+)', entry)
    if m:
        rest = re.sub(r'(?m)^\s*(eprint|url)\s*=.*$', '', entry)
        if m.group(1) in rest:
            entry = re.sub(r'(?m)^\s*(eprint|archivePrefix|primaryClass)\s*=.*\n', '', entry)
            dropped += 1
        else:
            kept += 1
    out.append(entry)
(here / 'refs.bib').write_text('% Generated by make_refs.py from ../paper-arxiv/references.bib; do not edit.\n' + ''.join(out))
print(f'refs.bib: eprint dropped from {dropped} entries, kept in {kept}')
